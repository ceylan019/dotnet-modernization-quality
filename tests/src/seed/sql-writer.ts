import type { ApplicantRow, ApplicationRow, Dataset, HistoryRow } from './records';
import { formatCents } from './fee';

const BATCH_ROWS = 500;

function nstr(value: string): string {
  return `N'${value.replace(/'/g, "''")}'`;
}

// SiteAddress and Phone are varchar columns, written as plain literals.
function str(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function nullable(value: string | null, format: (v: string) => string): string {
  return value === null ? 'NULL' : format(value);
}

function dt(timestamp: string): string {
  return `'${timestamp.replace(/-/g, '')}'`;
}

function date(value: string): string {
  return `'${value.replace(/-/g, '')}'`;
}

// Money literals keep every digit they were generated with (two or four decimals).
function money(value: string): string {
  return value;
}

function bit(value: boolean): string {
  return value ? '1' : '0';
}

function insertBatches<T>(table: string, columns: string[], rows: readonly T[], format: (row: T) => string): string {
  const out: string[] = [];
  for (let start = 0; start < rows.length; start += BATCH_ROWS) {
    const chunk = rows.slice(start, start + BATCH_ROWS);
    // IDENTITY_INSERT is per session, so it is switched on and off inside the same batch as the INSERT.
    out.push(
      `SET IDENTITY_INSERT dbo.${table} ON`,
      `INSERT INTO dbo.${table} (${columns.join(', ')}) VALUES`,
      chunk.map((row) => `(${format(row)})`).join(',\n'),
      `SET IDENTITY_INSERT dbo.${table} OFF`,
      'GO',
    );
  }
  return out.join('\n');
}

const applicantRow = (a: ApplicantRow) =>
  [
    a.id, nstr(a.firstName), nstr(a.lastName), nullable(a.email, nstr), nullable(a.phone, str),
    bit(a.isSenior), bit(a.isNonProfit), dt(a.createdAt),
  ].join(', ');

const applicationRow = (a: ApplicationRow) =>
  [
    a.id, str(a.referenceNumber), a.applicantId, str(a.permitTypeCode), str(a.siteAddress), formatCents(a.areaCents),
    nullable(a.description, nstr), str(a.status), date(a.submittedOn), dt(a.submittedAt), date(a.dueDate),
    money(a.fee), money(a.hst), money(a.total), dt(a.lastUpdatedAt),
  ].join(', ');

const historyRow = (h: HistoryRow) =>
  [
    h.id, h.applicationId, nullable(h.fromStatus, str), str(h.toStatus), dt(h.changedAt), nstr(h.changedBy),
    nullable(h.note, nstr),
  ].join(', ');

export function writeSql(data: Dataset): string {
  return [
    '-- Generated by tests/src/seed/generate.ts. Do not edit by hand.',
    'SET NOCOUNT ON',
    'GO',
    insertBatches(
      'Applicants',
      ['ApplicantId', 'FirstName', 'LastName', 'Email', 'Phone', 'IsSenior', 'IsNonProfit', 'CreatedAt'],
      data.applicants,
      applicantRow,
    ),
    insertBatches(
      'Applications',
      [
        'ApplicationId', 'ReferenceNumber', 'ApplicantId', 'PermitTypeCode', 'SiteAddress', 'AreaSqM', 'Description',
        'Status', 'SubmittedOn', 'SubmittedAt', 'DueDate', 'FeeAmount', 'HstAmount', 'TotalAmount', 'LastUpdatedAt',
      ],
      data.applications,
      applicationRow,
    ),
    insertBatches(
      'ApplicationStatusHistory',
      ['HistoryId', 'ApplicationId', 'FromStatus', 'ToStatus', 'ChangedAt', 'ChangedBy', 'Note'],
      data.history,
      historyRow,
    ),
    '',
  ].join('\n');
}
